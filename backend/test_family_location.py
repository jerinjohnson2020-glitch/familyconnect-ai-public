    # 3. Coordinate Bounds Validation
    # -------------------------------------------------------------
    def test_05_coordinate_bounds_validation(self):
        """
        Rejects invalid latitude (> 90 or < -90) and longitude (> 180 or < -180) with HTTP 422.
        """
        # Latitude > 90
        res1 = self.client.request("PUT", "/api/members/101/location", json_body={"latitude": 91.0, "longitude": 0.0}, token=self.token_marcus_h1)
        self.assertEqual(res1.status_code, 422)

        # Latitude < -90
        res2 = self.client.request("PUT", "/api/members/101/location", json_body={"latitude": -90.5, "longitude": 0.0}, token=self.token_marcus_h1)
        self.assertEqual(res2.status_code, 422)

        # Longitude > 180
        res3 = self.client.request("PUT", "/api/members/101/location", json_body={"latitude": 0.0, "longitude": 181.0}, token=self.token_marcus_h1)
        self.assertEqual(res3.status_code, 422)

        # Longitude < -180
        res4 = self.client.request("PUT", "/api/members/101/location", json_body={"latitude": 0.0, "longitude": -180.5}, token=self.token_marcus_h1)
        self.assertEqual(res4.status_code, 422)

