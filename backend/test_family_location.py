    # -------------------------------------------------------------
    def test_12_stale_location_indicator_flags_old_timestamps(self):
        """
        Locations older than 15 minutes are tagged with is_stale=True and correct age_minutes.
        """
        db = TestingSessionLocal()
        try:
            # Set Member 102's location timestamp to 30 minutes in the past
            past_30m = datetime.datetime.now(datetime.timezone.utc) - datetime.timedelta(minutes=30)
            m102 = db.query(Member).filter(Member.id == 102).first()
            m102.is_sharing_location = True
            m102.latitude = 28.6139
            m102.longitude = 77.2090
            m102.location_updated_at = past_30m
            db.commit()
        finally:
            db.close()

        res = self.client.request("GET", "/api/members/locations", token=self.token_admin_h1)
        self.assertEqual(res.status_code, 200)
        data = res.json()
        m102_item = next(m for m in data["members"] if m["member_id"] == 102)

        self.assertTrue(m102_item["is_sharing_location"])
        self.assertTrue(m102_item["is_stale"])
        self.assertGreaterEqual(m102_item["age_minutes"], 29)
        self.assertLessEqual(m102_item["age_minutes"], 32)

