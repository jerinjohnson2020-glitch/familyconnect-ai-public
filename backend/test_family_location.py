    # 2. Location Update & Server-Generated UTC Timestamp
    # -------------------------------------------------------------
    def test_03_consented_location_update_persists_coordinates_and_utc_time(self):
        """
        Once consented, valid coordinates update successfully.
        Timestamp is server-generated UTC.
        """
        before_update = datetime.datetime.now(datetime.timezone.utc)
        payload = {
            "latitude": 12.9716,
            "longitude": 77.5946,
            "accuracy_m": 15.5,
            "label": "Bengaluru MG Road"
        }
        res = self.client.request("PUT", "/api/members/101/location", json_body=payload, token=self.token_marcus_h1)
        self.assertEqual(res.status_code, 200)
        data = res.json()
        self.assertEqual(data["latitude"], 12.9716)
        self.assertEqual(data["longitude"], 77.5946)
        self.assertEqual(data["location_accuracy_m"], 15.5)
        self.assertEqual(data["location_label"], "Bengaluru MG Road")
        self.assertFalse(data["is_stale"])
        self.assertEqual(data["age_minutes"], 0)
        self.assertIsNotNone(data["location_updated_at"])

        db = TestingSessionLocal()
        try:
            m = db.query(Member).filter(Member.id == 101).first()
            self.assertEqual(m.latitude, 12.9716)
            self.assertEqual(m.longitude, 77.5946)
            self.assertIsNotNone(m.location_updated_at)
            # Timestamp check: within 10 seconds of before_update
            upd_aware = m.location_updated_at if m.location_updated_at.tzinfo else m.location_updated_at.replace(tzinfo=datetime.timezone.utc)
            delta = abs((upd_aware - before_update).total_seconds())
            self.assertLess(delta, 10.0)
        finally:
            db.close()

